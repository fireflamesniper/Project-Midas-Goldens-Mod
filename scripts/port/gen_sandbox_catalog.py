#!/usr/bin/env python3
"""Generate port/generated/sandbox_catalog.h from src/bondconstants.h.

The sandbox spawn menu (port/src/sandbox.c) lists every prop model and every
character body the game ships. Their display names come from the comments on
the PROP and BODIES enums, so this regenerates the tables when those change:

    python3 scripts/port/gen_sandbox_catalog.py
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "src", "bondconstants.h")
OUT = os.path.join(ROOT, "port", "generated", "sandbox_catalog.h")


def enum_block(text, name):
    m = re.search(r"typedef enum %s\s*\{(.*?)\}\s*%s;" % (name, name), text, re.S)
    if not m:
        sys.exit("enum %s not found in %s" % (name, SRC))
    return m.group(1)


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    with open(SRC, "r", encoding="utf-8", errors="replace") as f:
        text = f.read()

    props = []
    for line in enum_block(text, "PROP").splitlines():
        m = re.match(r"\s*(PROP_[A-Z0-9_]+)\s*,\s*/\*\s*(.*?)\s*\*/", line)
        if m and m.group(1) != "PROP_MAX":
            props.append((m.group(1), m.group(2)))

    bodies = []
    skip = False
    for line in enum_block(text, "BODIES").splitlines():
        line = line.strip()
        if line.startswith("#ifdef"):
            skip = True
            continue
        if line.startswith("#endif"):
            skip = False
            continue
        if skip:
            continue
        m = re.match(r"(BODY_[A-Za-z0-9_]+)\s*,", line)
        if line.startswith("HEAD_START"):
            break  # past this point the entries are heads, not bodies
        if m and "Floating_Arm" not in m.group(1):
            name = m.group(1)[len("BODY_"):].replace("_", " ").strip()
            bodies.append((m.group(1), name))

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by scripts/port/gen_sandbox_catalog.py from src/bondconstants.h - do not edit. */\n")
        f.write("#ifndef SANDBOX_CATALOG_H\n#define SANDBOX_CATALOG_H\n\n")
        f.write("static const struct { s16 model; const char *name; } sSandboxProps[] = {\n")
        for ident, name in props:
            f.write("    { %s, %s },\n" % (ident, c_str(name)))
        f.write("};\n\n")
        f.write("static const struct { s16 body; const char *name; } sSandboxBodies[] = {\n")
        for ident, name in bodies:
            f.write("    { %s, %s },\n" % (ident, c_str(name)))
        f.write("};\n\n#endif\n")
    print("wrote %s: %d props, %d bodies" % (OUT, len(props), len(bodies)))


if __name__ == "__main__":
    main()
